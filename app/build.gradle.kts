// The Jamendo API client id is a local credential: local.properties (git-ignored), a Gradle property or an environment
// variable named JAMENDO_CLIENT_ID. It is never in source control. Empty means "online source not configured".
val jamendoClientId: String = run {
    val local = Properties().apply {
        val file = rootProject.file("local.properties")
        if (file.exists()) file.inputStream().use { load(it) }
    }
    val raw = local.getProperty("JAMENDO_CLIENT_ID")
        ?: providers.gradleProperty("JAMENDO_CLIENT_ID").orNull
        ?: System.getenv("JAMENDO_CLIENT_ID")
        ?: ""
    raw.trim().filter { it.isLetterOrDigit() }
}

